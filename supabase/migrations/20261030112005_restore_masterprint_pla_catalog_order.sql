SET sort = CASE v.sku
  WHEN 'MP-PLA-BR' THEN 1
  WHEN 'MP-PLA-PT' THEN 2
  WHEN 'MP-PLA-CZ' THEN 3
  WHEN 'MP-PLA-MR' THEN 4
  WHEN 'MP-PLA-PR' THEN 5
  WHEN 'MP-PLA-DO' THEN 6
  WHEN 'MP-PLA-VM' THEN 7
  WHEN 'MP-PLA-AM' THEN 8
  WHEN 'MP-PLA-LA' THEN 9
  WHEN 'MP-PLA-RX' THEN 10
  WHEN 'MP-PLA-RS' THEN 11
  WHEN 'MP-PLA-VD' THEN 12
  WHEN 'MP-PLA-AZ' THEN 13
  WHEN 'MP-PLA-RBS' THEN 14
  WHEN 'MP-PLA-SK' THEN 15
  WHEN 'MP-PLA-VC' THEN 16
  WHEN 'MP-PLA-VE' THEN 17
  WHEN 'MP-PLA-CB' THEN 18
  WHEN 'MP-PLA-AE' THEN 19
END
FROM public.products p
WHERE p.id = v.product_id
  AND p.slug = 'masterprint-pla'
  AND v.sku IN (
    'MP-PLA-BR','MP-PLA-PT','MP-PLA-CZ','MP-PLA-MR','MP-PLA-PR',
    'MP-PLA-DO','MP-PLA-VM','MP-PLA-AM','MP-PLA-LA','MP-PLA-RX',
